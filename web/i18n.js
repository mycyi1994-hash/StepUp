export const LANGS = Object.keys(STRINGS);

function pick() {
  try {
    const query = new URLSearchParams(location.search).get('lang');
    if (LANGS.includes(query)) return query;
  } catch { /* No location (tests). */ }
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch { /* Storage can be disabled. */ }
  const preferred = (typeof navigator !== 'undefined' && (navigator.languages?.length ? navigator.languages : [navigator.language])) || [];
  return preferred.some(code => /^ko\b/i.test(code || '')) ? 'ko' : 'en';
}

export let lang = typeof document === 'undefined' ? 'ko' : pick();
const listeners = new Set();

/** 문구 하나 — {email} 같은 자리에 값을 넣는다. 없는 키는 한국어, 그것도 없으면 키 그대로. */
export function t(key, values = {}) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.ko[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in values ? String(values[name]) : `{${name}}`));
}

/** 화면의 [data-i18n] 글자와 [data-i18n-attr] 속성을 지금 언어로 채운다. */
export function apply(root = document) {
  document.documentElement.lang = lang;
  document.title = t('meta.title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('meta.description'));
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  // 줄바꿈 · 링크가 들어간 문구 — 이 파일에 있는 고정 문구만 넣는다(입력값은 넣지 않는다)
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split(':').map(part => part.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  }
}

export function setLang(next) {
  if (!LANGS.includes(next) || next === lang) return;
  lang = next;
  try { localStorage.setItem(STORE_KEY, next); } catch { /* Storage can be disabled. */ }
  try {
    const url = new URL(location.href);
    if (url.searchParams.has('lang')) { url.searchParams.set('lang', next); history.replaceState(history.state, '', url); }
  } catch { /* file:// */ }
  apply();
  listeners.forEach(fn => fn(lang));
}

/** 언어가 바뀌면 스크립트가 만든 글자(크루 명단 · 코스 · 안내 등)를 다시 쓴다. */
export function onLangChange(fn) { listeners.add(fn); }

// 처음 한 번 — 이 모듈을 처음 부르는 스크립트(site.js · waitlist.js)보다 먼저 돈다. 머리의 작은 스크립트가 감춰 둔 화면을 연다.
if (typeof document !== 'undefined') {
  apply();
  document.documentElement.classList.remove('i18n-pending');
}
